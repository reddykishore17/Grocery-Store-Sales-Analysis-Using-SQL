-- Ranks customers based on their total purchase amount
WITH CustomerSpending AS (
SELECT c.cust_name,SUM(od.total_price) AS total_spent
FROM customers c JOIN orders o ON c.cust_id = o.cust_id
JOIN order_details od ON o.ord_id = od.ord_id
GROUP BY o.cust_id)
SELECT cust_name,total_spent,
DENSE_RANK() OVER (ORDER BY total_spent DESC) AS customer_rank
FROM CustomerSpending;

-- Finds customers who have not made a purchase in the last 180 days
select c.cust_id,c.cust_name, MAX(o.order_date) as last_order_date,
    DATEDIFF(CURDATE(), MAX(o.order_date)) as days_since_last_order
from customers c join orders o on c.cust_id = o.cust_id
group by c.cust_id, c.cust_name
having days_since_last_order > 180
order by days_since_last_order DESC;


