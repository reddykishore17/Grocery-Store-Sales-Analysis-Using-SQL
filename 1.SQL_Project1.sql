-- Which suppliers contribute the most of sales of a specific category (by revenue)?
WITH RankedSuppliers AS (
    SELECT s.sup_name,c.cat_name,
        SUM(od.total_price) AS TotalRevenue,
        ROW_NUMBER() OVER(PARTITION BY c.cat_name ORDER BY SUM(od.total_price) DESC) as rank_num
    FROM Order_Details od
	JOIN Products p ON od.prod_id = p.prod_id
    JOIN Supplier s ON p.sup_id = s.sup_id
    JOIN Categories c ON p.cat_id = c.cat_id
    GROUP BY c.cat_name, s.sup_name)
SELECT sup_name,cat_name,TotalRevenue
FROM RankedSuppliers
WHERE rank_num = 1;

