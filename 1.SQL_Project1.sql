-- Identifies the best-selling product within each category based on total revenue
with ProductSales as (select c.cat_name,p.prod_name,
sum(od.total_price) as total_revenue,
row_number() over(partition by c.cat_name order by sum(od.total_price) desc) as rn
from order_details od 
join products p on od.prod_id = p.prod_id
join categories c on p.cat_id = c.cat_id
group by c.cat_name, p.prod_name)
select cat_name,prod_name,total_revenue
from ProductSales where rn = 1
order by total_revenue desc;

